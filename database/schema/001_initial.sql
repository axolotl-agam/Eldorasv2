CREATE DATABASE IF NOT EXISTS eldoras CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE eldoras;

CREATE TABLE IF NOT EXISTS players (
  uuid CHAR(36) PRIMARY KEY,
  username VARCHAR(16) NOT NULL,
  level SMALLINT UNSIGNED NOT NULL DEFAULT 1,
  experience BIGINT UNSIGNED NOT NULL DEFAULT 0,
  skill_points INT UNSIGNED NOT NULL DEFAULT 0,
  player_class VARCHAR(16) NULL,
  yang BIGINT UNSIGNED NOT NULL DEFAULT 0,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS player_skills (
  uuid CHAR(36) NOT NULL,
  skill_id VARCHAR(48) NOT NULL,
  learned_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY(uuid, skill_id),
  CONSTRAINT fk_player_skills_player FOREIGN KEY(uuid) REFERENCES players(uuid) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS economy_transactions (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  transaction_key CHAR(36) NOT NULL UNIQUE,
  actor_uuid CHAR(36) NULL,
  target_uuid CHAR(36) NULL,
  currency ENUM('YANG','WON') NOT NULL DEFAULT 'YANG',
  amount BIGINT UNSIGNED NOT NULL,
  reason VARCHAR(96) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  INDEX idx_economy_actor(actor_uuid, created_at),
  INDEX idx_economy_target(target_uuid, created_at)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS guilds (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(32) NOT NULL UNIQUE,
  leader_uuid CHAR(36) NOT NULL,
  level SMALLINT UNSIGNED NOT NULL DEFAULT 1,
  experience BIGINT UNSIGNED NOT NULL DEFAULT 0,
  bank_yang BIGINT UNSIGNED NOT NULL DEFAULT 0,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS guild_members (
  guild_id BIGINT UNSIGNED NOT NULL,
  player_uuid CHAR(36) NOT NULL UNIQUE,
  role ENUM('LEADER','OFFICER','MEMBER') NOT NULL DEFAULT 'MEMBER',
  joined_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY(guild_id, player_uuid),
  FOREIGN KEY(guild_id) REFERENCES guilds(id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS player_quests (
  player_uuid CHAR(36) NOT NULL,
  quest_id VARCHAR(64) NOT NULL,
  state ENUM('ACTIVE','COMPLETED','ABANDONED') NOT NULL DEFAULT 'ACTIVE',
  progress_json JSON NULL,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY(player_uuid, quest_id)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS player_pets (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  player_uuid CHAR(36) NOT NULL,
  pet_type VARCHAR(48) NOT NULL,
  level SMALLINT UNSIGNED NOT NULL DEFAULT 1,
  experience BIGINT UNSIGNED NOT NULL DEFAULT 0,
  expires_at TIMESTAMP NULL,
  data_json JSON NULL,
  INDEX idx_pets_owner(player_uuid)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS region_tax_ledger (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  region_id VARCHAR(24) NOT NULL,
  guild_id BIGINT UNSIGNED NOT NULL,
  amount_yang BIGINT UNSIGNED NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  INDEX idx_tax_region(region_id, created_at)
) ENGINE=InnoDB;
